/*
  Bullet-point PPTX export — deterministic, no AI.

  Builds a .pptx entirely from the lecture notes that already exist. It never
  calls Whisper, Ollama, or any API: the same stored `lecture_notes` that render
  on the page are laid out as slides. Running the export twice on the same
  lecture produces the same deck.

  This module is imported dynamically on click, so pptxgenjs is only downloaded
  when a user actually exports.
*/

import PptxGenJS from "pptxgenjs";
import type { NotesView } from "@/lib/notes-view";

export type PptxMeta = {
  title: string;
  subject: string;
  teacherName: string | null;
};

/* Palette lifted from the app's design tokens (globals.css), so the deck looks
   like Class AI rather than a default Office theme. */
const INK = "0B0C0E";
const SIGNAL = "D9A441";
const GRAPHITE = "8B919B";
const PAPER = "E9E7E2";

const MAX_BULLETS_PER_SLIDE = 6;
const FONT = "Segoe UI";

function plain(value: string): string {
  return value.replace(/\*\*/g, "").trim();
}

function newSlide(pptx: PptxGenJS) {
  const slide = pptx.addSlide();
  slide.background = { color: INK };
  slide.addText("CLASS AI", {
    x: 0.5,
    y: 7.0,
    w: 4,
    h: 0.3,
    fontFace: FONT,
    fontSize: 9,
    color: GRAPHITE,
    charSpacing: 2,
  });
  return slide;
}

/* A content slide with a legend, a heading, and a bullet list. Long lists are
   split across "(cont.)" slides so no slide overflows. */
function addBulletSlides(
  pptx: PptxGenJS,
  legend: string,
  heading: string,
  items: string[],
) {
  const clean = items.map(plain).filter(Boolean);
  if (clean.length === 0) return;

  for (let i = 0; i < clean.length; i += MAX_BULLETS_PER_SLIDE) {
    const chunk = clean.slice(i, i + MAX_BULLETS_PER_SLIDE);
    const slide = newSlide(pptx);
    const continued = i > 0;

    slide.addText(legend.toUpperCase(), {
      x: 0.5,
      y: 0.45,
      w: 12.3,
      h: 0.3,
      fontFace: FONT,
      fontSize: 11,
      color: SIGNAL,
      charSpacing: 2,
    });
    slide.addText(continued ? `${heading} (cont.)` : heading, {
      x: 0.5,
      y: 0.8,
      w: 12.3,
      h: 0.8,
      fontFace: FONT,
      fontSize: 26,
      bold: true,
      color: PAPER,
    });
    slide.addText(
      chunk.map((text) => ({
        text,
        options: { bullet: { indent: 18 }, color: PAPER, breakLine: true },
      })),
      {
        x: 0.6,
        y: 1.8,
        w: 12.1,
        h: 5.0,
        fontFace: FONT,
        fontSize: 16,
        color: PAPER,
        lineSpacingMultiple: 1.2,
        valign: "top",
        fit: "shrink",
        paraSpaceAfter: 10,
      },
    );
  }
}

export function buildLecturePptx(meta: PptxMeta, notes: NotesView): PptxGenJS {
  const pptx = new PptxGenJS();
  pptx.layout = "LAYOUT_WIDE";
  pptx.author = "Class AI";
  pptx.title = meta.title;

  /* Slide 1 — title */
  const title = newSlide(pptx);
  title.addText(meta.subject.toUpperCase(), {
    x: 0.7,
    y: 2.4,
    w: 12,
    h: 0.4,
    fontFace: FONT,
    fontSize: 14,
    color: SIGNAL,
    charSpacing: 3,
  });
  title.addText(meta.title, {
    x: 0.7,
    y: 2.85,
    w: 12,
    h: 1.6,
    fontFace: FONT,
    fontSize: 44,
    bold: true,
    color: PAPER,
    fit: "shrink",
  });
  title.addText(
    meta.teacherName ? `${meta.teacherName} · Generated by Class AI` : "Generated by Class AI",
    {
      x: 0.7,
      y: 4.5,
      w: 12,
      h: 0.4,
      fontFace: FONT,
      fontSize: 14,
      color: GRAPHITE,
    },
  );
  title.addShape("line", {
    x: 0.75,
    y: 2.35,
    w: 2.2,
    h: 0,
    line: { color: SIGNAL, width: 2 },
  });

  /* Slide 2 — quick summary / main topic */
  if (notes.quickSummary) {
    const summary = newSlide(pptx);
    summary.addText("QUICK UNDERSTANDING", {
      x: 0.5,
      y: 0.45,
      w: 12.3,
      h: 0.3,
      fontFace: FONT,
      fontSize: 11,
      color: SIGNAL,
      charSpacing: 2,
    });
    summary.addText(plain(notes.quickSummary), {
      x: 0.6,
      y: 1.6,
      w: 12.1,
      h: 4.4,
      fontFace: FONT,
      fontSize: 24,
      color: PAPER,
      valign: "top",
      lineSpacingMultiple: 1.3,
      fit: "shrink",
    });
  }

  /* Slides 3+ — important topics and key points */
  addBulletSlides(pptx, "Key concepts", "The main things this lecture taught", notes.keyPoints);
  addBulletSlides(
    pptx,
    "Definitions",
    "Definitions",
    notes.definitions.map((d) => `${d.term} — ${d.meaning}`),
  );
  addBulletSlides(pptx, "Important points", "What to carry out of this lecture", notes.importantPoints);
  addBulletSlides(pptx, "Examples", "Examples used in class", notes.examples);

  /* Final slide(s) — revision / exam points */
  const revision = notes.revisionPoints.length > 0 ? notes.revisionPoints : [];
  const examLines = notes.examQuestions.map((q) => q.question);
  addBulletSlides(pptx, "Quick revision", "Revise these", revision);
  addBulletSlides(pptx, "Potential exam questions", "Be able to answer", examLines);

  return pptx;
}

function fileNameFor(meta: PptxMeta): string {
  const base = `${meta.subject}-${meta.title}`
    .replace(/[^\w\s-]+/g, "")
    .trim()
    .replace(/\s+/g, "-")
    .slice(0, 80);
  return `${base || "class-ai-lecture"}.pptx`;
}

/* Builds and downloads the deck in the browser. */
export async function downloadLecturePptx(
  meta: PptxMeta,
  notes: NotesView,
): Promise<void> {
  const pptx = buildLecturePptx(meta, notes);
  await pptx.writeFile({ fileName: fileNameFor(meta) });
}
