import { Fragment, type ReactNode } from "react";
import { ExamQuestions, RevisionNotes } from "@/components/exam-revision";
import { ExportPptButton } from "@/components/export-ppt-button";
import { Flashcards } from "@/components/flashcards";
import { FullNotes } from "@/components/full-notes";
import { LectureChat } from "@/components/lecture-chat";
import { LectureTranscript } from "@/components/lecture-transcript";
import { Definitions, PointList } from "@/components/lecture-sections";
import { QuickSummary } from "@/components/quick-summary";
import { RevisionCards } from "@/components/revision-cards";
import { SectionNav } from "@/components/section-nav";
import type { NotesView } from "@/lib/notes-view";
import { toFlashcards } from "@/lib/flashcards";
import { toRevisionCards } from "@/lib/revision-cards";

/*
  The real lecture notes, rendered from what the analysis actually produced.

  Empty sections are left out entirely rather than shown as empty headings: the
  analysis is told to leave a field empty when the lecture did not cover it, so a
  missing section is information, not a gap to paper over. The jump bar is built
  from the sections that survive.
*/
export function LectureNotesView({
  lectureId,
  notes,
  transcript,
  meta,
}: {
  lectureId: string;
  notes: NotesView;
  transcript: string | null;
  meta: { title: string; subject: string; teacherName: string | null };
}) {
  const blocks: { href: string; label: string; node: ReactNode }[] = [];

  if (notes.quickSummary) {
    blocks.push({
      href: "#quick-understanding",
      label: "Quick",
      node: <QuickSummary summary={notes.quickSummary} />,
    });
  }

  if (notes.paragraphs.length > 0) {
    blocks.push({
      href: "#full-notes",
      label: "Notes",
      node: <FullNotes sections={[{ body: notes.paragraphs }]} />,
    });
  }

  if (notes.keyPoints.length > 0) {
    blocks.push({
      href: "#key-concepts",
      label: "Concepts",
      node: (
        <PointList
          anchor="key-concepts"
          legend="Key concepts"
          title="The main things this lecture taught"
          points={notes.keyPoints}
        />
      ),
    });
  }

  if (notes.definitions.length > 0) {
    blocks.push({
      href: "#definitions",
      label: "Definitions",
      node: <Definitions items={notes.definitions} />,
    });
  }

  if (notes.examples.length > 0) {
    blocks.push({
      href: "#examples",
      label: "Examples",
      node: (
        <PointList
          anchor="examples"
          legend="Examples"
          title="Examples used in class"
          points={notes.examples}
        />
      ),
    });
  }

  if (notes.importantPoints.length > 0) {
    blocks.push({
      href: "#important-points",
      label: "Important",
      node: (
        <PointList
          anchor="important-points"
          legend="Important points"
          title="What to carry out of this lecture"
          points={notes.importantPoints}
        />
      ),
    });
  }

  if (notes.examQuestions.length > 0) {
    blocks.push({
      href: "#exam-questions",
      label: "Questions",
      node: <ExamQuestions questions={notes.examQuestions} />,
    });
  }

  const revisionCards = toRevisionCards(notes);
  if (revisionCards.length > 0) {
    blocks.push({
      href: "#revision-cards",
      label: "Revision",
      node: <RevisionCards cards={revisionCards} />,
    });
  }

  const flashcards = toFlashcards(notes);
  if (flashcards.length > 0) {
    blocks.push({
      href: "#flashcards",
      label: "Flashcards",
      node: <Flashcards cards={flashcards} />,
    });
  }

  if (notes.revisionPoints.length > 0) {
    blocks.push({
      href: "#revision",
      label: "Cheat sheet",
      node: <RevisionNotes points={notes.revisionPoints} />,
    });
  }

  if (transcript && transcript.trim()) {
    blocks.push({
      href: "#transcript",
      label: "Transcript",
      node: <LectureTranscript transcript={transcript} />,
    });
  }

  /* Always available once a lecture has a transcript, which it has by the time
     notes exist. */
  blocks.push({
    href: "#ask",
    label: "Ask",
    node: <LectureChat lectureId={lectureId} />,
  });

  return (
    <>
      <SectionNav sections={blocks.map(({ href, label }) => ({ href, label }))} />

      <div className="mx-auto w-full max-w-5xl px-4 py-10 sm:px-6 sm:py-14">
        <div className="mb-8 flex flex-wrap items-center justify-between gap-4">
          <p className="legend">
            Generated by Class AI from this lecture&apos;s recording
          </p>
          <ExportPptButton meta={meta} notes={notes} />
        </div>

        <div className="space-y-14 sm:space-y-20">
          {blocks.map((block) => (
            <Fragment key={block.href}>{block.node}</Fragment>
          ))}
        </div>
      </div>
    </>
  );
}
